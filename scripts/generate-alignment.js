#!/usr/bin/env node
'use strict';
/**
 * generate-alignment.js — regenerate the two embedded alignment files from the
 * Master Alignment workbook.
 *
 * Why this exists: services/alignment-data.js and services/velocity-alignment.js
 * were hand-maintained, so they drifted from the workbook (P6 vs P10) and carried
 * a VP who had left the company. Both are now generated.
 *
 *   node scripts/generate-alignment.js "<path to AYVAZ Master Alignment PXX.xlsx>"
 *
 * Verify the roster afterwards with: node scripts/verify-alignment.js "<same path>"
 */
const XLSX = require('xlsx');
const fs   = require('fs');
const path = require('path');

const COL = { store: 1, name: 2, region: 4, city: 6, state: 7, rgm: 12, area: 15,
              ac: 16, ac_email: 18, rc: 19, vp: 22 };

const S = v => String(v ?? '').trim();

// Store numbers arrive from Excel as numerics, so 038876 reads back as 38876.
// Every downstream key (velocity "S######", alignment text, store_assignments)
// expects the zero-padded 6-digit form.
const SID = v => S(v).padStart(6, '0');

function load(file) {
  const wb   = XLSX.readFile(file);
  const sh   = wb.Sheets['Master Alignment'] || wb.Sheets[wb.SheetNames[0]];
  const rows = XLSX.utils.sheet_to_json(sh, { header: 1, blankrows: false }).slice(1);
  return rows.filter(r => S(r[COL.store]));
}

// "AYVAZ Master Alignment P10 REV 092926.xlsx" → "P10 REV 092926"
function revFromFilename(file) {
  const m = path.basename(file).match(/P\d+\s*REV\s*\d+/i);
  return m ? m[0].replace(/\s+/g, ' ') : 'UNKNOWN REV';
}

// Group into VP → RC → AC → stores, preserving workbook order at every level.
function hierarchy(rows) {
  const vps = new Map();
  for (const r of rows) {
    const vp = S(r[COL.vp]), rc = S(r[COL.rc]), ac = S(r[COL.ac]);
    if (!vps.has(vp)) vps.set(vp, new Map());
    const rcs = vps.get(vp);
    if (!rcs.has(rc)) rcs.set(rc, new Map());
    const acs = rcs.get(rc);
    if (!acs.has(ac)) acs.set(ac, { area: S(r[COL.area]), email: S(r[COL.ac_email]), stores: [] });
    acs.get(ac).stores.push(r);
  }
  return vps;
}

function buildAlignmentData(rows, rev) {
  const out = [];
  out.push(`AYVAZ PIZZA LLC — MASTER STORE ALIGNMENT (${rev})`);
  for (const [vp, rcs] of hierarchy(rows)) {
    out.push('', `VP of Operations: ${vp}`);
    for (const [rc, acs] of rcs) {
      out.push('', `  Region Coach: ${rc}`);
      for (const [ac, info] of acs) {
        out.push('', `    AC: ${ac} | ${info.area} | ${info.email}`);
        for (const r of info.stores) {
          const loc = [S(r[COL.city]), S(r[COL.state])].filter(Boolean).join(', ');
          out.push(`      ${SID(r[COL.store])} | ${loc} | RGM: ${S(r[COL.rgm]) || 'OPEN'}`);
        }
      }
    }
  }
  return `// AYVAZ Master Alignment — embedded directly in code.
// GENERATED by scripts/generate-alignment.js — do not edit by hand.
// Source: AYVAZ Master Alignment ${rev}.xlsx
// Last updated: ${rev}

const MASTER_ALIGNMENT_TEXT = \`
${out.join('\n')}
\`;

module.exports = { MASTER_ALIGNMENT_TEXT };
`;
}

function buildVelocityAlignment(rows, rev) {
  const lines = [];
  let lastRC = null, lastAC = null;
  for (const [vp, rcs] of hierarchy(rows)) {
    for (const [rc, acs] of rcs) {
      if (rc !== lastRC) { lines.push(`  // ── ${rc} Region ──`); lastRC = rc; }
      for (const [ac, info] of acs) {
        if (ac !== lastAC) { lines.push(`  // ${info.area} — ${ac}`); lastAC = ac; }
        for (const r of info.stores) {
          const rec = { name: S(r[COL.name]), area: info.area, area_coach: ac,
                        region_coach: rc, vp };
          lines.push(`  "S${SID(r[COL.store])}":${JSON.stringify(rec)},`);
        }
      }
    }
  }
  // Trailing comma is valid in an object literal, but strip it to match prior style.
  const last = lines.length - 1;
  lines[last] = lines[last].replace(/,$/, '');

  return `// =====================================================================
// VELOCITY ALIGNMENT — Full company store roster
// Maps store_id → { name, area, area_coach, region_coach, vp }
// GENERATED by scripts/generate-alignment.js — do not edit by hand.
// Last updated: ${rev}
// =====================================================================

const ALIGNMENT = {
${lines.join('\n')}
};

const stores = Object.values(ALIGNMENT);
const REGIONS     = [...new Set(stores.map(s => s.region_coach).filter(Boolean))].sort();
const AREAS       = [...new Set(stores.map(s => s.area_coach).filter(Boolean))].sort();
const AREA_COACHES = AREAS;

module.exports = { ALIGNMENT, REGIONS, AREAS, AREA_COACHES };
`;
}

function main() {
  const file = process.argv[2];
  if (!file) { console.error('usage: node scripts/generate-alignment.js <alignment.xlsx>'); process.exit(1); }
  if (!fs.existsSync(file)) { console.error(`not found: ${file}`); process.exit(1); }

  const rows = load(file);
  const rev  = revFromFilename(file);
  const root = path.join(__dirname, '..', 'services');

  fs.writeFileSync(path.join(root, 'alignment-data.js'),     buildAlignmentData(rows, rev));
  fs.writeFileSync(path.join(root, 'velocity-alignment.js'), buildVelocityAlignment(rows, rev));

  const vps = hierarchy(rows);
  const rcCount = [...vps.values()].reduce((n, m) => n + m.size, 0);
  const acSet = new Set(rows.map(r => S(r[COL.ac])));
  console.log(`Generated from ${rev}: ${rows.length} stores, ${acSet.size} ACs, ${rcCount} RCs, ${vps.size} VPs`);
  console.log('  services/alignment-data.js');
  console.log('  services/velocity-alignment.js');
}

main();
